import fs from 'node:fs'
import { describe, expect, it } from 'vitest'

const read = relative => fs.readFileSync(new URL(relative, import.meta.url), 'utf8')
const migration = read('../../../supabase/release/main/14_cod_financial_rpcs_review.sql')
const preflight = read('../../../supabase/release/main/14_cod_preflight_readonly.sql')
const postflight = read('../../../supabase/release/main/14_cod_postflight_readonly.sql')
const rollback = read('../../../supabase/release/main/14_cod_rollback_review.sql')
const localHarness = read('../../test-cod-main-release-local.mjs')
const runbook = read('../../../docs/runbooks/cutover-cod-release-14.md')
const readme = read('../../../supabase/release/main/README.md')
const summary = migration.match(/AS \$summary\$([\s\S]*?)\$summary\$/)?.[1] || ''
const reconcile = migration.match(/AS \$reconcile\$([\s\S]*?)\$reconcile\$/)?.[1] || ''

describe('Release principal COD 14 — contrato review-only', () => {
  it('mantiene el gate de revisión y el preflight no mutante', () => {
    expect(migration).toContain("RAISE EXCEPTION 'REVIEW_ONLY: 14_cod_financial_rpcs_review.sql requiere aprobacion, backup y prueba aislada'")
    expect(migration).toContain('recalcularcomisiondespacho_238b(uuid)')
    expect(preflight).toContain("'result', 'READ_ONLY_ONLY_NOT_AN_APPLY_APPROVAL'")
    expect(preflight).toContain("'missing_columns'")
    expect(preflight).toContain("'migration_history_table_present'")
  })

  it('define resumen tenant-scoped, solo lectura y con COD derivado del ledger', () => {
    expect(migration).toMatch(/LANGUAGE plpgsql\s+STABLE\s+SECURITY INVOKER/i)
    expect(summary).toMatch(/nd\.id = p_despacho_id AND nd\.cuenta_id = p_cuenta_id/i)
    expect(summary).toContain("'deuda_cod_usd'")
    expect(summary).toContain("'cobrado_usd'")
    expect(summary).toContain("'compensado_usd'")
    expect(summary).toContain("v_estado := 'parcial'")
    expect(summary).toContain("v_estado := 'manual_review'")
    expect(summary).not.toMatch(/\b(?:INSERT\s+INTO|UPDATE\s+\w+\s+SET|DELETE\s+FROM|TRUNCATE)\b/i)
  })

  it('serializa la conciliación atómica y preserva las dos fuentes JSON por separado', () => {
    expect(migration).toMatch(/LANGUAGE plpgsql\s+VOLATILE\s+SECURITY DEFINER/i)
    expect(reconcile).toContain('pg_advisory_xact_lock')
    expect(reconcile).toContain('COD_CONCILIACION_IDEMPOTENCIA_REUTILIZADA')
    expect(reconcile).toContain('COD_CONCILIACION_MONTO_NO_COINCIDE')
    expect(reconcile).toContain('COD_CONCILIACION_TASA_BS_INVALIDA')
    expect(reconcile).toContain('v_total_pago>v_deuda_cod+0.01')
    expect(reconcile).toContain('COALESCE(v_pago_json->>\'monto\',\'\') !~ \'^[0-9]+([.][0-9]{1,2})?$\'')
    expect(reconcile).toContain('COALESCE(v_pago_json->>\'monto_bs\',\'\') !~ \'^[0-9]+([.][0-9]{1,2})?$\'')
    expect(reconcile).toContain("'cobro_destino_pagado',(v_deuda_cod-v_total_pago)<=0")
    expect(reconcile).toContain('v_deuda_cod-v_total_pago<=0 THEN')
    expect(reconcile).toContain("'excedente_usd',GREATEST(0,round(v_total_pago-v_deuda_cod,2))")
    expect(reconcile).not.toContain('v_deuda_cod-v_total_pago<=0.01')
    expect(postflight).toContain('rate_snapshot_contract_present')
    expect(postflight).toContain('cod_completion_requires_zero_debt')
    expect(postflight).toContain('cod_allows_maximum_one_cent_overpayment')
    expect(reconcile).toContain('tasa_snapshot')
    expect(reconcile).toContain('equivalente_usd')
    expect(reconcile).toContain('tasa_confirmada_en')
    expect(reconcile).toContain('v_pagos_snapshot')
    expect(reconcile).toContain('COD_CONCILIACION_ACTOR_NO_AUTORIZADO')
    expect(reconcile).toContain('v_formas_cliente_nuevas')
    expect(reconcile).toContain('v_formas_pago_nuevas')
    expect(reconcile).toContain('FROM jsonb_array_elements(v_formas_cliente) WITH ORDINALITY')
    expect(reconcile).toContain('FROM jsonb_array_elements(v_formas_pago) WITH ORDINALITY')
    expect(reconcile).toContain('forma_pago=v_formas_pago_nuevas')
    expect(reconcile).toContain('forma_pago_cliente=v_formas_cliente_nuevas')
    expect(reconcile).toContain('recalcularcomisiondespacho_238b')
    expect(migration).toMatch(/GRANT EXECUTE ON FUNCTION public\.registrar_pago_externo_cobro_idempotente[\s\S]*?TO service_role/i)
  })

  it('rollback revisa marcadores y conserva datos y tabla idempotente', () => {
    expect(rollback).toContain('ROLLBACK_14_COD_RECONCILE_OWNER_MISMATCH')
    expect(rollback).toContain('per-Bs-payment rate snapshots')
    expect(rollback).toContain('DROP FUNCTION IF EXISTS public.registrar_pago_externo_cobro_idempotente')
    expect(rollback).toContain('DROP FUNCTION IF EXISTS public.resumen_financiero_despacho')
    expect(rollback).not.toMatch(/DROP TABLE|DELETE FROM|TRUNCATE|CASCADE/i)
  })

  it('harness exige modo local, verifica gate y limita conexión a PostgreSQL loopback', () => {
    expect(localHarness).toContain("process.argv[2] !== '--verify-local'")
    expect(localHarness).toContain("host: '127.0.0.1'")
    expect(localHarness).toContain('server_version_num')
    expect(localHarness).toContain('never reads env')
    expect(localHarness).toContain('migration.replace(gate,')
    expect(localHarness).toContain('RPC summary post-parcial')
    expect(localHarness).toContain('RPC summary post-final')
    expect(localHarness).toContain('efectivo Bs calcula USD por la tasa snapshot del pago')
    expect(localHarness).toContain('abonos parciales conservan snapshots independientes sin revaluar el anterior')
    expect(localHarness).toContain('dos JSON parciales conservan marcador')
    expect(localHarness).toContain('la misma clave no acepta payload distinto')
    expect(localHarness).not.toMatch(/SUPABASE_URL|DATABASE_URL|management\.supabase\.com/i)
  })

  it('runbook mantiene NO-GO, exige backup/aprobación y excluye RPC exclusiva de staging', () => {
    expect(runbook).toContain('PREPARACIÓN / NO-GO')
    expect(runbook).toContain('snapshot fijo')
    expect(runbook).toContain('monto recibido en Bs')
    expect(runbook).toContain('Backup verificable')
    expect(runbook).toContain('no se ejecutó SQL remoto')
    expect(runbook).toContain('regularizar_cod_efectivo_atomico_staging')
    expect(runbook).toContain('supabase db push')
    expect(runbook).toContain('autorización explícita')
    expect(readme).toContain('no se promueven')
  })
})
